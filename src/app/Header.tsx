import { formatMonth } from '../domain/calendar';
import { MODE_LABELS } from '../domain/scenario';
import { MODEL_VERSION } from '../domain/version';
import { href, type Route } from './router';
import { isDirty, useStore } from './store';

const NAV: [Route, string][] = [
  ['overview', 'Overview'],
  ['lab', 'Scenario lab'],
  ['cohorts', 'Loan groups'],
  ['decision', 'Decision room'],
  ['validation', 'Validation lab'],
  ['learn', 'Learn'],
  ['glossary', 'Glossary'],
  ['methodology', 'Methodology'],
];

export function Header({ route }: { route: Route }) {
  const { state, dispatch, active } = useStore();
  const p = state.portfolio.meta;
  return (
    <header className="app-header">
      <div className="header-inner">
        <span className="brand">Mortgage Prepayment &amp; Servicing Lab</span>
        <div className="meta-row" aria-label="Portfolio and model">
          <span>
            <strong>{p.name}</strong> <a href={href('start')} style={{ fontSize: '0.85rem' }} data-testid="change-portfolio">Change portfolio</a>
          </span>
          <span className="badge synthetic" title="Every loan is generated by a seeded synthetic generator. No real borrower or market data.">
            Synthetic data
          </span>
          <span>As of {formatMonth(p.asOfMonth)}</span>
          <span>
            {MODE_LABELS[active.draft.mode]} model · <span className="muted">version {MODEL_VERSION}</span>
          </span>
          <label className="row" style={{ gap: '0.3rem', fontWeight: 400 }}>
            <span>Viewing</span>
            <select value={state.activeId} onChange={(e) => dispatch({ type: 'setActive', id: e.target.value })} aria-label="Active scenario">
              {state.slots.map((s) => (
                <option key={s.draft.scenarioId} value={s.draft.scenarioId}>
                  {s.draft.scenarioId === state.baselineId ? `Baseline (frozen): ${s.draft.name}` : s.draft.name}
                  {s.draft.scenarioId !== state.baselineId && isDirty(s) ? ' · edited, not yet run' : ''}
                </option>
              ))}
            </select>
          </label>
          <label className="row" style={{ gap: '0.3rem', fontWeight: 400 }}>
            <span>Role</span>
            <select value={state.role} onChange={(e) => dispatch({ type: 'setRole', role: e.target.value as typeof state.role })} aria-label="Role (changes detail level, not formulas)">
              <option value="gm">General manager</option>
              <option value="director">Director</option>
              <option value="analyst">Analyst</option>
            </select>
          </label>
          <StorageBadge />
        </div>
      </div>
      <nav className="main-nav" aria-label="Main">
        {NAV.map(([r, label]) => (
          <a key={r} href={href(r)} aria-current={route === r ? 'page' : undefined}>
            {label}
          </a>
        ))}
      </nav>
    </header>
  );
}

function StorageBadge() {
  const { state } = useStore();
  const st = state.storage;
  if (st.status === 'unavailable') return <span className="badge err" title={st.message ?? ''}>Not saved: storage unavailable</span>;
  if (st.status === 'loading') return <span className="badge">Checking local storage…</span>;
  if (st.savedAt) return <span className="badge ok" title={`Last saved ${new Date(st.savedAt).toLocaleString()}`}>Saved on this device</span>;
  return <span className="badge">Not yet saved</span>;
}
