interface ShellUi {
  keysOpen: boolean;
  setKeysOpen: (v: boolean) => void;
  shortcutsOn: boolean;
  setShortcutsOn: (v: boolean) => void;
}
const UiCtx = createContext<ShellUi | null>(null);
export const useShellUi = () => useContext(UiCtx)!;

export function ShellUiProvider({ children }: { children: ReactNode }) {
  const [keysOpen, setKeysOpen] = useState(false);
  const [shortcutsOn, setShortcutsOn] = usePref('shortcuts', true);
  return <UiCtx.Provider value={{ keysOpen, setKeysOpen, shortcutsOn, setShortcutsOn }}>{children}</UiCtx.Provider>;
}

