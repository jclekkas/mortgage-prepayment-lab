const GLYPH = { up: '▲', down: '▼', flat: '►' } as const;

function ScenarioTabs() {
  const { state, dispatch, baseline } = useStore();
  const owner = usePerspective() === 'owner';
  const ctx = currentContext(state);
  const current = (s: Slot) => (s.run.output && !stalenessReason(s.run.output, ctx) ? s.run.output : null);
  const bo = current(baseline);
  const addNew = () => {
    const n = state.slots.length;
    const draft = { ...structuredClone(baseline.run.outputInput ?? baseline.draft), scenarioId: newScenarioId(), name: `Scenario ${n}`, baselineId: state.baselineId };
    dispatch({ type: 'addScenario', scenario: draft });
  };
  return (
    <div className="row" style={{ gap: 6 }}>
      <div className="scen-tabs" role="group" aria-label="Active scenario" data-testid="scenario-tabs">
        {state.slots.map((s, i) => {
          const isBase = s.draft.scenarioId === state.baselineId;
          const out = current(s);
          let line2: ReactNode;
          if (!out) line2 = s.run.status === 'running' ? 'Calculating…' : 'Not run';
          else {
            const sm = out.summary;
            const val = owner ? `Average life ${years(sm.wal)}` : `Value ${usd(sm.servicingNpv, { compact: true })}`;
            if (isBase || !bo) line2 = <>{val} {isBase && <span>frozen</span>}</>;
            else {
              const b = bo.summary;
              const tr = owner ? trendOf('wal', b.wal, sm.wal) : trendOf('npv', b.servicingNpv, sm.servicingNpv);
              const d = owner
                ? (sm.wal !== null && b.wal !== null ? `${sm.wal - b.wal >= 0 ? '+' : '−'}${Math.abs(sm.wal - b.wal).toFixed(2)} yrs` : '')
                : usd(sm.servicingNpv - b.servicingNpv, { compact: true, signed: true });
              const cls = tr?.tone === 'good' ? 'chg-good' : tr?.tone === 'bad' ? 'chg-bad' : '';
              line2 = <>{val} {tr && <span className={cls}>{tr.tone !== 'flat' ? `${d} ` : ''}<span aria-hidden="true">{GLYPH[tr.direction]}</span> {tr.word}</span>}</>;
            }
          }
          return (
            <button key={s.draft.scenarioId} type="button" className="scen-tab" aria-pressed={s.draft.scenarioId === state.activeId}
              onClick={() => dispatch({ type: 'setActive', id: s.draft.scenarioId })} data-testid={`scenario-tab-${i + 1}`}>
              <span className="l1">
                <span className="num" aria-hidden="true">{i + 1}</span>
                {isBase && <><LockIcon /><span className="sr-only">Frozen baseline:</span></>}
                <span className="nm">{s.draft.name}</span>
                {!isBase && isDirty(s) && s.run.output && <span className="ed">· edited</span>}
              </span>
              <span className="l2">{line2}</span>
            </button>
          );
        })}
      </div>
      <button type="button" className="ghost" onClick={addNew} disabled={state.slots.length >= 4} title={state.slots.length >= 4 ? 'Up to four scenarios including the baseline' : 'A new scenario starts from the baseline assumptions'} data-testid="new-scenario">
        + New scenario
      </button>
    </div>
  );
}

function RunControls() {
  const { state, active, baseline, run, cancel, draftErrors } = useStore();
  const { errors } = useFieldStatus();
  const fieldIssues = Object.values(errors);
  const d = active.draft;
  const isBase = d.scenarioId === state.baselineId;
  const running = active.run.status === 'running';
  const dirty = isDirty(active);
  const n = diffInputs(baseline.run.outputInput ?? baseline.draft, d).length;
  const changes = n === 0 ? 'Matches the baseline' : `${n} change${n === 1 ? '' : 's'} from baseline`;
  const text = isBase
    ? 'Baseline is frozen. Pick a scenario to edit.'
    : fieldIssues.length ? 'Finish or reset the highlighted fields before running.'
    : running ? 'Calculating…'
    : active.run.status === 'error' ? 'Run failed. See the message below.'
    : `${changes} · ${dirty ? 'edited, press Run' : 'results up to date'}`;
  return (
    <>
      <span className={`status-line${!isBase && (dirty || active.run.status === 'error') ? ' edited' : ''}`} data-testid="dirty-badge" role="status">{text}</span>
      {running && <button type="button" onClick={() => cancel(d.scenarioId)} data-testid="cancel">Cancel</button>}
      <button type="button" className="primary" onClick={() => { if (!running) run(d.scenarioId); }} disabled={draftErrors.length > 0 || fieldIssues.length > 0 || isBase} aria-disabled={running} aria-busy={running} data-testid="run" id="run-scenario"
        title={isBase ? 'The baseline is frozen. Pick a scenario to run.' : 'Run the active scenario (R)'}>
        <span aria-hidden="true">▷</span> {running ? 'Running…' : 'Run'}
      </button>
      {draftErrors.length > 0 && (
        <div className="notice err run-errors" role="alert" style={{ flexBasis: '100%' }} data-testid="run-errors">
          {draftErrors.map((e) => <div key={e.field + e.message}>{e.message}</div>)}
        </div>
      )}
    </>
  );
}

/** Single-key shortcuts. WCAG 2.1.4: they can be turned off in the Keys dialog. */
export function useShortcuts(route: Route) {
  const { state, dispatch, active, run, draftErrors } = useStore();
  const { errors } = useFieldStatus();
  const { keysOpen, setKeysOpen, shortcutsOn } = useShellUi();
  const live = useRef({ state, active, draftErrors, keysOpen, shortcutsOn, route, errors });
  live.current = { state, active, draftErrors, keysOpen, shortcutsOn, route, errors };
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      const L = live.current;
      if (L.route === 'start') return;
      if (e.key === 'Escape' && L.keysOpen) { setKeysOpen(false); return; }
      if (!L.shortcutsOn || e.metaKey || e.ctrlKey || e.altKey) return;
      const t = e.target as HTMLElement | null;
      const tag = t?.tagName;
      if (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT' || t?.isContentEditable) return;
      const k = e.key;
      if (k === '?') { setKeysOpen(!L.keysOpen); e.preventDefault(); return; }
      if (L.keysOpen) return;
      if (/^[1-4]$/.test(k)) {
        const s = L.state.slots[Number(k) - 1];
        if (s) { dispatch({ type: 'setActive', id: s.draft.scenarioId }); e.preventDefault(); }
        return;
      }
      const lk = k.toLowerCase();
      if (lk === 'r') {
        const a = L.active;
        if (a.draft.scenarioId !== L.state.baselineId && a.run.status !== 'running' && L.draftErrors.length === 0 && Object.keys(L.errors).length === 0) { run(a.draft.scenarioId); e.preventDefault(); }
        return;
      }
      if (lk === 'p') { dispatch({ type: 'setGoal', goal: L.state.goal === 'investor' ? 'servicing' : 'investor' }); e.preventDefault(); return; }
      const nav: Record<string, Route> = { o: 'overview', l: 'lab', g: 'cohorts', d: 'decision', f: 'validation' };
      if (nav[lk]) { navigate(nav[lk]); e.preventDefault(); }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [dispatch, run, setKeysOpen]);
}

export function KeysDialog() {
  const { keysOpen, setKeysOpen, shortcutsOn, setShortcutsOn } = useShellUi();
  const ref = useRef<HTMLDivElement>(null);
  const opener = useRef<Element | null>(null);
  useEffect(() => {
    if (keysOpen) {
      opener.current = document.activeElement;
      ref.current?.querySelector<HTMLElement>('button, input')?.focus();
    } else if (opener.current instanceof HTMLElement) {
      opener.current.focus();
      opener.current = null;
    }
  }, [keysOpen]);
  if (!keysOpen) return null;
  // Keep Tab inside the dialog.
  const trap = (e: React.KeyboardEvent) => {
    if (e.key !== 'Tab') return;
    const f = [...(ref.current?.querySelectorAll<HTMLElement>('button, input') ?? [])];
    if (!f.length) return;
    const first = f[0], last = f[f.length - 1];
    if (e.shiftKey && document.activeElement === first) { last.focus(); e.preventDefault(); }
    else if (!e.shiftKey && document.activeElement === last) { first.focus(); e.preventDefault(); }
  };
  return (
    <div className="dialog-backdrop" onClick={() => setKeysOpen(false)}>
      <div className="dialog" role="dialog" aria-modal="true" aria-labelledby="keys-h" ref={ref} onClick={(e) => e.stopPropagation()} onKeyDown={trap} data-testid="keys-dialog">
        <h2 id="keys-h">Keyboard shortcuts</h2>
        <dl>
          <dt>R</dt><dd>Run the active scenario</dd>
          <dt>1–4</dt><dd>Switch scenario (1 is the baseline)</dd>
          <dt>P</dt><dd>Toggle Servicer / Loan owner</dd>
          <dt>O L G D F</dt><dd>Overview, Scenario lab, Loan groups, Decision room, Forecast check</dd>
          <dt>?</dt><dd>Show or hide this panel</dd>
          <dt>Esc</dt><dd>Close this panel</dd>
        </dl>
        <p className="muted">Shortcuts pause while you type in a field, and ignore keys held with Ctrl, Cmd or Alt.</p>
        <label className="row" style={{ gap: 8 }}>
          <input type="checkbox" checked={shortcutsOn} onChange={(e) => setShortcutsOn(e.target.checked)} data-testid="shortcuts-toggle" />
          Single-key shortcuts on (turn off if they get in the way of speech input or other assistive technology)
        </label>
        <div className="row" style={{ marginTop: 12 }}>
          <button type="button" className="primary" onClick={() => setKeysOpen(false)}>Close</button>
        </div>
      </div>
    </div>
  );
}
