#!/usr/bin/env node
// Writes THIRD_PARTY_LICENSES.md from the installed dependency tree (production and dev).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const rows = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path.startsWith('node_modules/')) continue;
  const name = path.slice(path.lastIndexOf('node_modules/') + 13);
  let license = info.license;
  if (!license) {
    const pj = join(root, path, 'package.json');
    if (existsSync(pj)) license = JSON.parse(readFileSync(pj, 'utf8')).license;
  }
  rows.push({ name, version: info.version, license: typeof license === 'string' ? license : JSON.stringify(license ?? 'UNKNOWN'), dev: !!info.dev });
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const counts = rows.reduce((m, r) => ((m[r.license] = (m[r.license] ?? 0) + 1), m), {});
const direct = new Set([...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.devDependencies ?? {})]);
const out = [
  '# Third-party licenses',
  '',
  'Generated by `npm run licenses` from package-lock.json. Only runtime dependencies (`dev: no`) ship in the built app.',
  '',
  '## Summary by license',
  '',
  ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`),
  '',
  '## Direct dependencies',
  '',
  '| Package | Version | License | Dev only |',
  '| --- | --- | --- | --- |',
  ...rows.filter((r) => direct.has(r.name)).map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.dev ? 'yes' : 'no'} |`),
  '',
  '## All packages',
  '',
  '| Package | Version | License | Dev only |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.dev ? 'yes' : 'no'} |`),
  '',
];
writeFileSync(join(root, 'THIRD_PARTY_LICENSES.md'), out.join('\n'));
console.log(`Wrote ${rows.length} packages. ${Object.entries(counts).map(([l, n]) => `${l}=${n}`).join(', ')}`);
